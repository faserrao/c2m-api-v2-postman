#!/usr/bin/env python3
"""
validate_all_collections_against_spec.py

Validates ALL generated Postman collections against the OpenAPI spec
(which is derived from the EBNF Data Dictionary — single source of truth).

This extends validate_collections_against_spec.py with:
  - Scans ALL active *.json files in postman/generated/ by default
  - Adds ENUM VALUE validation for example collections (non-placeholder bodies)
  - Validates BOTH typed collections (<string>/<oneOf> placeholders) and
    example collections (real values from faker/catalog)
  - Reports per-collection PASS/FAIL/WARN/SKIP summary + all error details

Checks performed:
  - Unknown fields: field in request body not present in spec schema
  - Missing required: required spec field absent from request body
  - Invalid enum: string value not in the spec's allowed enum list
  - Bad endpoint: path+method not found in spec (WARN, not FAIL)
  - Bad JSON: body cannot be parsed (WARN)

Usage:
    python3 scripts/validation/validate_all_collections_against_dd.py
    python3 scripts/validation/validate_all_collections_against_dd.py \\
        --spec openapi/c2mapiv2-openapi-spec-final.yaml \\
        --dir postman/generated \\
        --report reports/dd-validation-report.md \\
        --all          # include stale/debug collections too

Exit code: 0 = no FAILs, 1 = at least one FAIL found.
WARNs (unknown endpoint, bad JSON) do not affect exit code.
"""

import json
import os
import re
import sys
import glob
import argparse
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

# --------------------------------------------------------------------------- #
# Repository paths                                                             #
# --------------------------------------------------------------------------- #
_SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(_SCRIPT_DIR))
DEFAULT_SPEC = os.path.join(REPO, "openapi/c2mapiv2-openapi-spec-final.yaml")
DEFAULT_DIR = os.path.join(REPO, "postman/generated")

# Active collections: generated by the current pipeline and uploaded to Postman.
# Stale / one-off / debug files are excluded by default (use --all to include).
ACTIVE_COLLECTIONS = {
    "c2mapiv2-linked-collection-flat.json",          # main typed (linked) collection
    "c2mapiv2-test-collection-flat.json",            # main test collection (random values, flat)
    "c2mapiv2-getting-started-linked-collection.json",  # GS typed collection
    "c2mapiv2-getting-started-test-collection.json",    # GS test collection (faker values)
    "c2mapiv2-real-world-use-cases-collection.json", # real-world curated examples
    "c2mapiv2-getting-started-curated-collection.json", # GS curated examples
}

PLACEHOLDER = re.compile(r"^<[^>]+>$")

# --------------------------------------------------------------------------- #
# Path translation: curated/test collections use legacy /jobs/submit/... paths #
# The OpenAPI spec uses the short canonical paths.                            #
# --------------------------------------------------------------------------- #
PATH_ALIASES: Dict[str, str] = {
    "/jobs/submit/single/doc":                   "/static",
    "/jobs/submit/single/pdf/addressCapture":    "/static/address-capture",
    "/jobs/submit/single/pdf/split":             "/batch/split",
    "/jobs/submit/single/pdf/split/addressCapture": "/batch/split/address-capture",
    "/jobs/submit/multi/doc":                    "/mail-merge",
    "/jobs/submit/multi/doc/merge":              "/mail-merge",
    "/jobs/submit/multi/zip":                    "/batch/zip",
    "/jobs/submit/multi/zip/addressCapture":     "/batch/zip/address-capture",
    # Postman path-param style → OpenAPI style
    "/auth/tokens/:tokenId/revoke":              "/auth/tokens/{tokenId}/revoke",
}


# --------------------------------------------------------------------------- #
# Spec loading and $ref resolution                                             #
# --------------------------------------------------------------------------- #
def load_spec(path: str) -> Dict:
    try:
        import yaml
    except ImportError:
        print("ERROR: pyyaml required — run: pip install pyyaml", file=sys.stderr)
        sys.exit(1)
    with open(path) as f:
        return yaml.safe_load(f)


def deref(spec: Dict, schema: Any) -> Any:
    """Follow $ref chains (up to 20 hops)."""
    seen = 0
    while isinstance(schema, dict) and "$ref" in schema and seen < 20:
        ref = schema["$ref"]
        node = spec
        for part in ref.lstrip("#/").split("/"):
            node = node[part.replace("~1", "/").replace("~0", "~")]
        schema = node
        seen += 1
    return schema


def is_placeholder(value: Any) -> bool:
    return isinstance(value, str) and bool(PLACEHOLDER.match(value))


def any_placeholder(obj: Any) -> bool:
    if is_placeholder(obj):
        return True
    if isinstance(obj, dict):
        return any(any_placeholder(v) for v in obj.values())
    if isinstance(obj, list):
        return any(any_placeholder(v) for v in obj)
    return False


# --------------------------------------------------------------------------- #
# Schema traversal                                                             #
# --------------------------------------------------------------------------- #
def collect_properties(schema: Dict, spec: Dict, _depth: int = 0) -> Tuple[Dict, List[str]]:
    """
    Collect all property schemas and required field names from a schema,
    recursively following $ref / allOf. oneOf/anyOf branches contribute
    their properties to the "known" set (for unknown-field detection) but
    do NOT add to required (since only one branch needs to be satisfied).
    """
    if _depth > 12:
        return {}, []
    schema = deref(spec, schema)
    if not isinstance(schema, dict):
        return {}, []

    props: Dict = {}
    required: List[str] = list(schema.get("required", []))

    for name, prop_schema in schema.get("properties", {}).items():
        props[name] = prop_schema

    for sub in schema.get("allOf", []):
        sub_props, sub_req = collect_properties(sub, spec, _depth + 1)
        props.update(sub_props)
        required.extend(sub_req)

    for sub in schema.get("oneOf", []) + schema.get("anyOf", []):
        sub_props, _ = collect_properties(sub, spec, _depth + 1)
        for k, v in sub_props.items():
            if k not in props:
                props[k] = v

    return props, required


def enum_values(schema: Dict, spec: Dict, _depth: int = 0) -> Optional[List]:
    """Return the enum list from a schema, or None if there is no enum constraint."""
    if _depth > 8:
        return None
    schema = deref(spec, schema)
    if not isinstance(schema, dict):
        return None
    if "enum" in schema:
        return schema["enum"]
    for sub in schema.get("allOf", []) + schema.get("oneOf", []) + schema.get("anyOf", []):
        result = enum_values(sub, spec, _depth + 1)
        if result is not None:
            return result
    return None


def resolve_path(path: str) -> Tuple[str, bool]:
    """
    Translate a legacy collection path to its canonical spec path.
    Returns (canonical_path, was_aliased).
    """
    if path in PATH_ALIASES:
        return PATH_ALIASES[path], True
    return path, False


def endpoint_schema(spec: Dict, path: str, method: str) -> Optional[Dict]:
    """Return the requestBody JSON schema for an operation, or None."""
    canonical, _ = resolve_path(path)
    op = spec.get("paths", {}).get(canonical, {}).get(method.lower())
    if not op:
        return None
    try:
        return op["requestBody"]["content"]["application/json"]["schema"]
    except KeyError:
        return None


# --------------------------------------------------------------------------- #
# Core validator                                                               #
# --------------------------------------------------------------------------- #
def validate_value(
    value: Any,
    schema: Dict,
    spec: Dict,
    loc: str,
    check_enums: bool,
    _depth: int = 0,
) -> List[str]:
    """
    Recursively validate a value against a schema.
    Returns a list of human-readable error strings.

    Placeholder values (<string>, <oneOf>, etc.) are always accepted without
    type/enum checks — they appear in typed (linked) collections intentionally.
    """
    if _depth > 15:
        return []

    schema = deref(spec, schema)
    if not isinstance(schema, dict):
        return []

    # Placeholders pass unconditionally.
    if is_placeholder(value):
        return []

    errors: List[str] = []

    # allOf: satisfy every sub-schema
    for sub in schema.get("allOf", []):
        errors += validate_value(value, sub, spec, loc, check_enums, _depth + 1)

    # oneOf/anyOf without own properties: skip branch discrimination
    # (placeholder-safe; discriminator awareness is a Phase 2 concern)
    is_pure_composition = (
        ("oneOf" in schema or "anyOf" in schema)
        and "properties" not in schema
        and "required" not in schema
    )
    if is_pure_composition:
        return errors

    stype = schema.get("type")

    # --- Enum check (scalars only, non-placeholder) ---
    if check_enums and not any_placeholder(value):
        ev = enum_values(schema, spec)
        if ev is not None and value not in ev:
            errors.append(
                f"{loc}: INVALID ENUM '{value}' — allowed: {ev}"
            )
            return errors  # enum mismatch makes deeper checks meaningless

    # --- Object ---
    if stype == "object" or "properties" in schema or "required" in schema:
        if not isinstance(value, dict):
            errors.append(f"{loc}: expected object, got {type(value).__name__}")
            return errors

        props, required = collect_properties(schema, spec)
        addl = schema.get("additionalProperties")
        allow_extra = addl is True or isinstance(addl, dict) or (not props and addl is None)

        # Unknown fields
        if not allow_extra and props:
            for k in value:
                if k not in props:
                    errors.append(f"{loc}.{k}: UNKNOWN FIELD (not in DD schema)")

        # Missing required (only when body carries real values)
        if not any_placeholder(value):
            for req in required:
                if req not in value:
                    errors.append(f"{loc}: MISSING REQUIRED field '{req}'")

        # Recurse into known properties
        for k, v in value.items():
            if k in props:
                errors += validate_value(
                    v, props[k], spec, f"{loc}.{k}", check_enums, _depth + 1
                )

        return errors

    # --- Array ---
    if stype == "array" or "items" in schema:
        if not isinstance(value, list):
            errors.append(f"{loc}: expected array, got {type(value).__name__}")
            return errors
        item_schema = schema.get("items")
        if item_schema:
            for i, el in enumerate(value):
                errors += validate_value(
                    el, item_schema, spec, f"{loc}[{i}]", check_enums, _depth + 1
                )
        return errors

    # Scalars with no enum constraint: accept any value.
    return errors


# --------------------------------------------------------------------------- #
# Collection iteration                                                         #
# --------------------------------------------------------------------------- #
def iter_requests(collection: Dict):
    def walk(items, folder=""):
        for it in items:
            if "item" in it:
                yield from walk(it["item"], it.get("name", folder))
            elif "request" in it:
                req = it["request"]
                url = req.get("url", {})
                if isinstance(url, dict):
                    raw_path = url.get("path", [])
                    path = "/" + "/".join(
                        str(p) for p in raw_path if p not in ("{{baseUrl}}", "")
                    )
                else:
                    path = str(url)
                raw = (req.get("body") or {}).get("raw") or ""
                yield {
                    "folder": folder,
                    "name": it.get("name", "(unnamed)"),
                    "method": (req.get("method") or "GET").upper(),
                    "path": path,
                    "raw": raw,
                }

    yield from walk(collection.get("item", []))


# --------------------------------------------------------------------------- #
# Per-collection validation driver                                             #
# --------------------------------------------------------------------------- #
PASS = "PASS"
FAIL = "FAIL"
WARN = "WARN"
SKIP = "SKIP"


def validate_collection(spec: Dict, collection: Dict, check_enums: bool = True) -> List[Dict]:
    results = []
    for req in iter_requests(collection):
        path = req["path"]
        method = req["method"]
        raw = req["raw"].strip()

        if not raw:
            results.append({**req, "status": SKIP, "errors": [], "note": "no request body"})
            continue

        try:
            body = json.loads(raw)
        except json.JSONDecodeError as exc:
            results.append({
                **req, "status": WARN, "errors": [],
                "note": f"body is not valid JSON: {exc}"
            })
            continue

        canonical, aliased = resolve_path(path)
        schema = endpoint_schema(spec, path, method.lower())
        if schema is None:
            results.append({
                **req, "status": WARN, "errors": [],
                "note": f"endpoint '{method} {path}' not found in spec"
            })
            continue

        alias_note = f" (aliased from {path})" if aliased else ""
        errs = validate_value(body, schema, spec, "body", check_enums=check_enums)
        results.append({
            **req,
            "status": FAIL if errs else PASS,
            "errors": errs,
            "note": alias_note.strip(),
        })

    return results


# --------------------------------------------------------------------------- #
# Output formatters                                                            #
# --------------------------------------------------------------------------- #
STATUS_ICON = {PASS: "✅", FAIL: "❌", WARN: "⚠️ ", SKIP: "⏭️ "}
STATUS_ABBR = {PASS: "PASS", FAIL: "FAIL", WARN: "WARN", SKIP: "SKIP"}


def _tally(results: List[Dict]) -> Dict[str, int]:
    counts = {PASS: 0, FAIL: 0, WARN: 0, SKIP: 0}
    for r in results:
        counts[r["status"]] += 1
    return counts


def print_collection_report(coll_name: str, results: List[Dict], verbose: bool):
    tally = _tally(results)
    icon = "❌" if tally[FAIL] > 0 else ("⚠️ " if tally[WARN] > 0 else "✅")
    summary = "  ".join(f"{STATUS_ABBR[s]}={tally[s]}" for s in (PASS, FAIL, WARN, SKIP))
    print(f"\n{icon} {coll_name}")
    print(f"   {summary}")

    for r in results:
        if r["status"] in (PASS, SKIP) and not verbose:
            continue
        icon_r = STATUS_ICON[r["status"]]
        label = f"{r['method']} {r['path']}  [{r['name']}]"
        print(f"   {icon_r} {label}")
        if r["note"]:
            print(f"       note: {r['note']}")
        for err in r["errors"]:
            print(f"       • {err}")


def write_markdown_report(
    path: str,
    spec_path: str,
    all_results: List[Tuple[str, List[Dict]]],
    total_tally: Dict[str, int],
):
    lines = [
        "# DD Validation Report — All Collections",
        "",
        f"**Spec:** `{spec_path}`",
        "",
        "## Summary",
        "",
        "| Collection | PASS | FAIL | WARN | SKIP |",
        "| --- | --- | --- | --- | --- |",
    ]
    for coll_name, results in all_results:
        t = _tally(results)
        lines.append(f"| {coll_name} | {t[PASS]} | {t[FAIL]} | {t[WARN]} | {t[SKIP]} |")

    lines += [
        "",
        f"**Totals — PASS={total_tally[PASS]}  FAIL={total_tally[FAIL]}  "
        f"WARN={total_tally[WARN]}  SKIP={total_tally[SKIP]}**",
        "",
        "---",
        "",
        "## Findings",
        "",
    ]

    for coll_name, results in all_results:
        lines.append(f"### {coll_name}")
        lines.append("")
        fails = [r for r in results if r["status"] == FAIL]
        warns = [r for r in results if r["status"] == WARN]
        if not fails and not warns:
            lines.append("_No issues found._")
        for r in fails + warns:
            icon_r = STATUS_ICON[r["status"]]
            lines.append(f"**{icon_r} {r['method']} {r['path']}** — {r['name']}")
            if r["note"]:
                lines.append(f"- note: {r['note']}")
            for err in r["errors"]:
                lines.append(f"- {err}")
            lines.append("")

    Path(path).parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"\nReport written to: {path}")


# --------------------------------------------------------------------------- #
# Main                                                                         #
# --------------------------------------------------------------------------- #
def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Validate all Postman collections against the EBNF Data Dictionary (via OpenAPI spec)."
    )
    parser.add_argument(
        "--spec",
        default=DEFAULT_SPEC,
        help=f"Path to OpenAPI spec (default: {os.path.relpath(DEFAULT_SPEC, REPO)})",
    )
    parser.add_argument(
        "--dir",
        default=DEFAULT_DIR,
        help=f"Directory of Postman collection JSON files (default: {os.path.relpath(DEFAULT_DIR, REPO)})",
    )
    parser.add_argument(
        "--all",
        action="store_true",
        default=False,
        help="Include stale/debug collections (default: active pipeline collections only)",
    )
    parser.add_argument(
        "--no-enum",
        action="store_true",
        default=False,
        help="Skip enum value validation (structural checks only)",
    )
    parser.add_argument(
        "--report",
        default=None,
        help="Write Markdown report to this path",
    )
    parser.add_argument(
        "--verbose", "-v",
        action="store_true",
        default=False,
        help="Print PASS and SKIP results too (default: only FAIL and WARN)",
    )
    args = parser.parse_args(argv)

    spec_path = args.spec if os.path.isabs(args.spec) else os.path.join(REPO, args.spec)
    collections_dir = args.dir if os.path.isabs(args.dir) else os.path.join(REPO, args.dir)

    # Load spec
    if not os.path.exists(spec_path):
        print(f"ERROR: spec not found: {spec_path}", file=sys.stderr)
        sys.exit(1)
    print(f"Loading spec: {os.path.relpath(spec_path, REPO)}")
    spec = load_spec(spec_path)
    print(f"  {len(spec.get('paths', {}))} endpoints loaded\n")

    # Discover collection files
    all_files = sorted(glob.glob(os.path.join(collections_dir, "*.json")))
    if args.all:
        collection_files = all_files
    else:
        collection_files = [
            f for f in all_files
            if os.path.basename(f) in ACTIVE_COLLECTIONS
        ]

    if not collection_files:
        print(f"No collections found in {collections_dir}", file=sys.stderr)
        sys.exit(0)

    check_enums = not args.no_enum
    print(f"Validating {len(collection_files)} collection(s)"
          f"  [enum-check: {'ON' if check_enums else 'OFF'}]\n")
    print("=" * 72)

    all_results: List[Tuple[str, List[Dict]]] = []
    total_tally: Dict[str, int] = {PASS: 0, FAIL: 0, WARN: 0, SKIP: 0}

    for fpath in collection_files:
        coll_name = os.path.basename(fpath)
        try:
            with open(fpath) as f:
                collection = json.load(f)
        except Exception as exc:
            print(f"\n⚠️  {coll_name}: could not load — {exc}")
            continue

        results = validate_collection(spec, collection, check_enums=check_enums)
        all_results.append((coll_name, results))
        print_collection_report(coll_name, results, args.verbose)

        t = _tally(results)
        for s in (PASS, FAIL, WARN, SKIP):
            total_tally[s] += t[s]

    # Grand total
    print("\n" + "=" * 72)
    print(
        f"TOTAL — PASS={total_tally[PASS]}  FAIL={total_tally[FAIL]}  "
        f"WARN={total_tally[WARN]}  SKIP={total_tally[SKIP]}"
    )

    if args.report:
        report_path = args.report if os.path.isabs(args.report) else os.path.join(REPO, args.report)
        write_markdown_report(report_path, spec_path, all_results, total_tally)

    sys.exit(1 if total_tally[FAIL] > 0 else 0)


if __name__ == "__main__":
    main()
